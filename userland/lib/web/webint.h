/* libweb internals shared by http.c, tls.c and job.c */
#ifndef WEBINT_H
#define WEBINT_H
#include "webplat.h"
#include "bearssl.h"

#define CONN_BUF 16384

typedef struct tls_state tls_state_t;   /* tls.c */

/* one TCP connection, plain or TLS */
typedef struct wconn {
    int fd;
    int tls;
    char host[256];
    int port;
    tls_state_t *t;
    /* I/O control for the request that uses the connection */
    volatile int *cancel;
    int idle_ms;
    int err;                    /* why the last I/O failed (WEB_E_* / E_*) */
    char why[200];              /* details for err */
    int eof;                    /* the peer closed (TCP) */
    uint64_t idle_since;        /* in the session's pool */
    /* buffered reading for the HTTP parser */
    uint8_t buf[CONN_BUF];
    size_t bpos, blen;
} wconn_t;

/* TLS session parameters kept for resumption */
typedef struct {
    char host[256];
    int port;
    br_ssl_session_parameters p;
    int valid;
} tls_cache_t;

typedef struct cookie cookie_t;

#define POOL_MAX 4
#define TLS_CACHE_MAX 8
struct web_session {
    wp_mutex_t lock;
    int flags;
    cookie_t *cookies;          /* linked list */
    int ncookies;
    wconn_t *pool[POOL_MAX];    /* idle kept-alive connections */
    tls_cache_t cache[TLS_CACHE_MAX];
    int cache_next;
    br_x509_trust_anchor *extra;    /* web_session_add_ca_pem */
    int nextra;
    br_x509_trust_anchor *all;      /* built-in + extra (when there are extra) */
    int nall;
};

/* the built-in trust anchors (generated by tools/mktrust.py) */
extern const br_x509_trust_anchor web_trust_anchors[];
extern const unsigned web_trust_anchors_count;

/* tls.c */
int  tls_start(web_session_t *s, wconn_t *c);       /* handshake on a connected socket; 0 or error */
long tls_read(wconn_t *c, void *b, size_t n);       /* bytes, 0 = end, < 0 error (c->err) */
int  tls_write(wconn_t *c, const void *b, size_t n);  /* 0 or error; flushes */
void tls_close(wconn_t *c, int notify);
void tls_info(wconn_t *c, char *out, size_t n);
void tls_free_session(web_session_t *s);

/* raw socket I/O with the connection's timeouts and cancel flag (http.c) */
long conn_raw_read(wconn_t *c, void *b, size_t n);  /* > 0, 0 = end, < 0 error (c->err set) */
int  conn_raw_write(wconn_t *c, const void *b, size_t n);
int  conn_fail(wconn_t *c, int err, const char *why);

#endif
