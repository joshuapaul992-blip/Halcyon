#!/usr/bin/env python3
"""Render TrueType fonts into 8-bit alpha glyph bitmaps for the Halcyon kernel.

Output: <outdir>/fonts.c and <outdir>/fonts.h
Glyphs are rendered with grayscale anti-aliasing for ranges of Unicode code
points (the kernel's text is UTF-8): Latin, Greek, Cyrillic and common
symbols for the UI fonts, plus box drawing for the monospace font; the big
display fonts only carry Latin-1.
"""
import os
import sys

# Use FreeType's classic TrueType bytecode interpreter (v35): full hinting,
# like early-2000s font rendering, instead of the modern v40 default. This
# must be set before Pillow loads FreeType (it is read at library init).
_props = [p for p in os.environ.get("FREETYPE_PROPERTIES", "").split() if not p.startswith("truetype:interpreter-version=")]
os.environ["FREETYPE_PROPERTIES"] = " ".join(_props + ["truetype:interpreter-version=35"])

from PIL import Image, ImageDraw, ImageFont

FONTDIR = "/usr/share/fonts/truetype/dejavu"
BASIC = [(0x20, 0x7E), (0xA0, 0xFF), (0xFFFD, 0xFFFD)]
TEXT = [(0x20, 0x7E), (0xA0, 0x24F), (0x370, 0x3FF), (0x400, 0x4FF), (0x1E00, 0x1EFF),
        (0x2010, 0x2027), (0x2030, 0x203A), (0x2044, 0x2044), (0x20AC, 0x20AC), (0x2116, 0x2116),
        (0x2122, 0x2122), (0x2190, 0x2195), (0x2212, 0x2212), (0x221E, 0x221E), (0x2248, 0x2248),
        (0x2260, 0x2265), (0xFFFD, 0xFFFD)]
MONO = TEXT[:-1] + [(0x2500, 0x25A0), (0xFFFD, 0xFFFD)]
FONTS = [
    # name,        file,                     px, ranges
    ("font_ui",      "DejaVuSans.ttf",          11, TEXT),
    ("font_ui_bold", "DejaVuSans-Bold.ttf",     11, TEXT),
    ("font_title",   "DejaVuSans-Bold.ttf",     12, TEXT),
    ("font_mono",    "DejaVuSansMono.ttf",      12, MONO),
    ("font_large",   "DejaVuSans-Bold.ttf",     20, BASIC),
    ("font_huge",    "DejaVuSans-Bold.ttf",     34, BASIC),
    ("font_small",   "DejaVuSans.ttf",           9, TEXT),
]


def render(name, path, px, ranges):
    font = ImageFont.truetype(path, px)
    ascent, descent = font.getmetrics()
    glyphs = []
    bitmap = bytearray()
    for code in (c for lo, hi in ranges for c in range(lo, hi + 1)):
        ch = chr(code)
        adv = int(round(font.getlength(ch)))
        x0, y0, x1, y1 = font.getbbox(ch)
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        off = len(bitmap)
        if w and h:
            im = Image.new("L", (w, h), 0)
            ImageDraw.Draw(im).text((-x0, -y0), ch, font=font, fill=255)
            bitmap += im.tobytes()
        glyphs.append((x0, y0, w, h, adv, off))
    return dict(name=name, ascent=ascent, descent=descent, height=ascent + descent,
                glyphs=glyphs, bitmap=bitmap, ranges=ranges)


def main():
    out = sys.argv[1]
    os.makedirs(out, exist_ok=True)
    fonts = [render(n, os.path.join(FONTDIR, f), px, r) for n, f, px, r in FONTS]
    with open(os.path.join(out, "fonts.h"), "w") as h:
        h.write("/* generated by tools/mkfont.py */\n#ifndef GEN_FONTS_H\n#define GEN_FONTS_H\n#include <stdint.h>\n")
        h.write("typedef struct { int8_t xoff, yoff; uint8_t w, h, adv; uint32_t off; } glyph_t;\n")
        h.write("typedef struct { uint32_t first, last, index; } font_range_t;\n")
        h.write("typedef struct { const char *name; int height, ascent, descent, nranges;\n"
                "                 const font_range_t *ranges; const glyph_t *glyphs; const uint8_t *bitmap; } font_t;\n")
        for f in fonts:
            h.write("extern const font_t %s;\n" % f["name"])
        h.write("#endif\n")
    with open(os.path.join(out, "fonts.c"), "w") as c:
        c.write("/* generated by tools/mkfont.py */\n#include \"fonts.h\"\n")
        for f in fonts:
            n = f["name"]
            c.write("static const uint8_t %s_bits[%d] = {" % (n, max(1, len(f["bitmap"]))))
            b = f["bitmap"] or b"\0"
            for i, v in enumerate(b):
                if i % 32 == 0:
                    c.write("\n")
                c.write("%d," % v)
            c.write("\n};\n")
            c.write("static const glyph_t %s_glyphs[%d] = {\n" % (n, len(f["glyphs"])))
            for g in f["glyphs"]:
                c.write("{%d,%d,%d,%d,%d,%d},\n" % g)
            c.write("};\n")
            c.write("static const font_range_t %s_ranges[%d] = {\n" % (n, len(f["ranges"])))
            idx = 0
            for lo, hi in f["ranges"]:
                c.write("{%d,%d,%d},\n" % (lo, hi, idx))
                idx += hi - lo + 1
            c.write("};\n")
            c.write("const font_t %s = { \"%s\", %d, %d, %d, %d, %s_ranges, %s_glyphs, %s_bits };\n"
                    % (n, n, f["height"], f["ascent"], f["descent"], len(f["ranges"]), n, n, n))


if __name__ == "__main__":
    main()
