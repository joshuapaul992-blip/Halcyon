#!/usr/bin/env python3
"""Render TrueType fonts into 8-bit alpha glyph bitmaps for the Halcyon kernel.

Output: <outdir>/fonts.c and <outdir>/fonts.h
Characters 32..255 (ISO-8859-1) are rendered with grayscale anti-aliasing.
"""
import os
import sys
from PIL import Image, ImageDraw, ImageFont

FONTDIR = "/usr/share/fonts/truetype/dejavu"
FONTS = [
    # name,        file,                     px
    ("font_ui",      "DejaVuSans.ttf",          11),
    ("font_ui_bold", "DejaVuSans-Bold.ttf",     11),
    ("font_title",   "DejaVuSans-Bold.ttf",     12),
    ("font_mono",    "DejaVuSansMono.ttf",      12),
    ("font_large",   "DejaVuSans-Bold.ttf",     20),
    ("font_huge",    "DejaVuSans-Bold.ttf",     34),
    ("font_small",   "DejaVuSans.ttf",           9),
]
FIRST, LAST = 32, 255


def render(name, path, px):
    font = ImageFont.truetype(path, px)
    ascent, descent = font.getmetrics()
    glyphs = []
    bitmap = bytearray()
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        if 127 <= code < 160:
            ch = "?"
        adv = int(round(font.getlength(ch)))
        x0, y0, x1, y1 = font.getbbox(ch)
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        off = len(bitmap)
        if w and h:
            im = Image.new("L", (w, h), 0)
            ImageDraw.Draw(im).text((-x0, -y0), ch, font=font, fill=255)
            bitmap += im.tobytes()
        glyphs.append((x0, y0, w, h, adv, off))
    return dict(name=name, ascent=ascent, descent=descent, height=ascent + descent,
                glyphs=glyphs, bitmap=bitmap)


def main():
    out = sys.argv[1]
    os.makedirs(out, exist_ok=True)
    fonts = [render(n, os.path.join(FONTDIR, f), px) for n, f, px in FONTS]
    with open(os.path.join(out, "fonts.h"), "w") as h:
        h.write("/* generated by tools/mkfont.py */\n#ifndef GEN_FONTS_H\n#define GEN_FONTS_H\n#include <stdint.h>\n")
        h.write("typedef struct { int8_t xoff, yoff; uint8_t w, h, adv; uint32_t off; } glyph_t;\n")
        h.write("typedef struct { const char *name; int height, ascent, descent, first, last;\n"
                "                 const glyph_t *glyphs; const uint8_t *bitmap; } font_t;\n")
        for f in fonts:
            h.write("extern const font_t %s;\n" % f["name"])
        h.write("#endif\n")
    with open(os.path.join(out, "fonts.c"), "w") as c:
        c.write("/* generated by tools/mkfont.py */\n#include \"fonts.h\"\n")
        for f in fonts:
            n = f["name"]
            c.write("static const uint8_t %s_bits[%d] = {" % (n, max(1, len(f["bitmap"]))))
            b = f["bitmap"] or b"\0"
            for i, v in enumerate(b):
                if i % 32 == 0:
                    c.write("\n")
                c.write("%d," % v)
            c.write("\n};\n")
            c.write("static const glyph_t %s_glyphs[%d] = {\n" % (n, len(f["glyphs"])))
            for g in f["glyphs"]:
                c.write("{%d,%d,%d,%d,%d,%d},\n" % g)
            c.write("};\n")
            c.write("const font_t %s = { \"%s\", %d, %d, %d, %d, %d, %s_glyphs, %s_bits };\n"
                    % (n, n, f["height"], f["ascent"], f["descent"], FIRST, LAST, n, n))


if __name__ == "__main__":
    main()
