#!/usr/bin/env python3
"""Generate kernel/fs/ntfs_upcase.c: the NTFS $UpCase table (one UTF-16 unit
-> its uppercase for each of the 65536 BMP code units) as compact runs.

The table is derived from the Unicode character database of the Python that
runs this script (unicodedata), with the rules Windows' own table follows:

  - simple (one-to-one) uppercase mappings only: a character whose full
    uppercase is several characters (U+00DF sharp s, ligatures) keeps its
    titlecase mapping if that is one character (Greek with ypogegrammeni,
    U+1F80 -> U+1F88), else maps to itself;
  - only reversible pairs: c -> U only if U lowercases back to c. This drops
    the one-way mappings Windows leaves out (U+00B5 micro sign, U+0131
    dotless i, U+017F long s, final sigma U+03C2, the Greek symbol forms
    U+03D0.., titlecase digraphs U+01C5.., U+0345, U+1E9B, U+1FBE);
  - the repertoire of Unicode 5.1, the version Windows Vista SP1 / 7 built
    their table from (Windows 8 and later format volumes with the same
    mappings): pairs involving characters added in Unicode 5.2 or later are
    left out (EXCLUDE below, from the Unicode version history).

Surrogates and the private use area map to themselves. The generated file is
committed; run this script again only to change the rules:

    python3 tools/mkntfsupcase.py > kernel/fs/ntfs_upcase.c
"""
import sys
import unicodedata

# characters (either side of a case pair) added in Unicode 5.2 and later
EXCLUDE = [
    (0x2C70, 0x2C70), (0x2C7E, 0x2C7F),         # 5.2: turned alpha, s/z with swash tail
    (0x0524, 0x0527), (0xA660, 0xA661),         # 6.0
    (0xA78D, 0xA78D), (0xA790, 0xA791), (0xA7A0, 0xA7A9),
    (0x0265, 0x0265),                           # 6.0 (capital U+A78D)
    (0x2CEB, 0x2CEE), (0x2CF2, 0x2CF3),         # 5.2 / 6.1 Coptic
    (0x10C7, 0x10C7), (0x10CD, 0x10CD), (0x2D27, 0x2D27), (0x2D2D, 0x2D2D),   # 6.1 Georgian
    (0xA792, 0xA793), (0xA7AA, 0xA7AA), (0x0266, 0x0266),                     # 6.1
    (0x0528, 0x052F), (0x037F, 0x037F), (0x03F3, 0x03F3),                     # 7.0
    (0xA698, 0xA69B), (0xA794, 0xA79F), (0xA7AB, 0xA7AD), (0xA7B0, 0xA7B1),
    (0x025C, 0x025C), (0x0261, 0x0261), (0x026C, 0x026C), (0x029E, 0x029E), (0x0287, 0x0287),
    (0x13F0, 0x13F5), (0x13F8, 0x13FD), (0xAB70, 0xABBF), (0x13A0, 0x13EF),   # 8.0 Cherokee
    (0xA7B2, 0xA7B7), (0xAB53, 0xAB53), (0x029D, 0x029D),
    (0x1C80, 0x1C88), (0xA7AE, 0xA7AE), (0x026A, 0x026A),                     # 9.0
    (0x1C90, 0x1CBF),                                                         # 11.0 Mtavruli
    (0xA7B8, 0xA7B9),
    (0xA7BA, 0xA7BF), (0xA7C2, 0xA7C6), (0x0282, 0x0282), (0x1D8E, 0x1D8E),   # 12.0
    (0xA7C7, 0xA7CA), (0xA7F5, 0xA7F6),                                       # 13.0
    (0x2C2F, 0x2C2F), (0x2C5F, 0x2C5F), (0xA7C0, 0xA7C1), (0xA7D0, 0xA7D9),   # 14.0
    (0xA7CB, 0xA7CF), (0xA7DA, 0xA7DC),                                       # 16.0
]
# (older characters that only gained a case partner later, such as U+0265 or
# the Cherokee capitals U+13A0.., are listed too: a pair is dropped if either
# side is listed)


def excluded(c):
    return any(a <= c <= b for a, b in EXCLUDE)


def upper(c):
    if 0xD800 <= c < 0xE000 or 0xE000 <= c < 0xF900:
        return c
    ch = chr(c)
    u = ch.upper()
    if len(u) != 1:
        u = ch.title()
        if len(u) != 1:
            return c
    uc = ord(u)
    if uc == c or uc >= 0x10000 or u.lower() != ch:
        return c
    if excluded(c) or excluded(uc):
        return c
    return uc


def runs(table):
    """(first, count, delta, step): `count` characters from `first`, every
    `step`th one, map to themselves + delta"""
    out = []
    c = 0
    while c < 0x10000:
        d = table[c] - c
        if not d:
            c += 1
            continue
        # contiguous run
        n = 1
        while c + n < 0x10000 and table[c + n] - (c + n) == d:
            n += 1
        # alternating run (c, c+2, ...; the odd ones in between map to themselves)
        m = 1
        while c + 2 * m < 0x10000 and table[c + 2 * m] - (c + 2 * m) == d and table[c + 2 * m - 1] == c + 2 * m - 1:
            m += 1
        if m > n and m > 1:
            out.append((c, m, d, 2))
            c += 2 * m - 1
        else:
            out.append((c, n, d, 1))
            c += n
    return out


def main():
    table = [upper(c) for c in range(0x10000)]
    rs = runs(table)
    w = sys.stdout.write
    w("/* Halcyon OS - the NTFS $UpCase table (generated by tools/mkntfsupcase.py\n"
      " * from the Unicode %s character database; do not edit).\n"
      " *\n"
      " * Simple, reversible uppercase pairs of the Unicode 5.1 repertoire: the\n"
      " * mappings of the table Windows writes (see the script for the rules).\n"
      " * %d characters change; %d runs below. */\n" % (unicodedata.unidata_version,
                                                       sum(1 for c in range(0x10000) if table[c] != c), len(rs)))
    w('#include "fs/ntfs_mkfs.h"\n\n')
    w("/* first, count, step, delta: `count` code units from `first`, every\n"
      " * `step`th one, map to unit + delta (mod 65536) */\n")
    w("static const struct { u16 first, count; u8 step; i32 delta; } runs[] = {\n")
    line = "   "
    for f, n, d, s in rs:
        item = " {0x%04X,%d,%d,%d}," % (f, n, s, d)
        if len(line) + len(item) > 96:
            w(line + "\n")
            line = "   "
        line += item
    w(line + "\n};\n\n")
    w("void ntfs_upcase_table(u16 *t) {\n"
      "    for (u32 c = 0; c < 65536; c++) t[c] = (u16)c;\n"
      "    for (u32 i = 0; i < sizeof runs / sizeof runs[0]; i++)\n"
      "        for (u32 k = 0; k < runs[i].count; k++) {\n"
      "            u32 c = runs[i].first + k * runs[i].step;\n"
      "            t[c] = (u16)(c + (u32)runs[i].delta);\n"
      "        }\n"
      "}\n")


if __name__ == "__main__":
    main()
